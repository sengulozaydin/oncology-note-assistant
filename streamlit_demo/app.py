from pathlib import Path
import html

import streamlit as st

from evidence import select_evidence, highlighted_context
from qa_client import QAClient, QAError

st.set_page_config(page_title='OncoNote Explorer', page_icon='🩺')
st.title('OncoNote Explorer')
st.write('Ask English questions about oncology notes and inspect the source evidence.')
st.caption('For research use only. Not a clinical decision tool.')

st.markdown('''<style>
div[data-testid="stTextInput"] label p, div[data-testid="stSelectbox"] label p {
    color:#ff8c42!important;font-weight:600;
}
div[data-testid="stTextInput"] input, div[data-testid="stSelectbox"] [data-baseweb="select"] > div {
    border-color:#ff8c42!important;
}
.note-preview,.note-rest,.source-context{line-height:1.6;overflow-wrap:anywhere;max-width:100%;white-space:normal}
details.read-more{display:inline}
details.read-more summary{display:inline;cursor:pointer;color:#ff8c42;list-style:none}
details.read-more summary::-webkit-details-marker{display:none}
.less-label{display:none}
details.read-more[open] .more-label{display:none}
details.read-more[open] .less-label{display:inline}
.note-rest{margin-top:0.4rem}
.source-context{white-space:pre-wrap}
h3.result-heading{color:#3b638f!important}
</style>''', unsafe_allow_html=True)


@st.cache_resource(show_spinner=False)
def get_qa_client():
    return QAClient()


notes_folder = Path(__file__).resolve().parent.parent / 'mt_onc_50'
note_files = sorted(notes_folder.glob('*.txt'), key=lambda p: int(p.stem.rsplit('_', 1)[-1]))
if not note_files:
    st.error('No .txt notes were found in the mt_onc_50 folder.')
    st.stop()

selected_note = st.selectbox('Select a note', note_files, format_func=lambda file: file.name)
try:
    note_text = selected_note.read_text(encoding='utf-8')
except (OSError, UnicodeError):
    st.error('The selected note could not be read as UTF-8 text. Select another note.')
    st.stop()
lines = note_text.splitlines()
preview = '<br>'.join(html.escape(line) for line in lines[:6])
remaining = '<br>'.join(html.escape(line) for line in lines[6:])
if remaining:
    preview += ('&nbsp;<details class="read-more"><summary>'
                '<span class="more-label">Read more</span><span class="less-label">Read less</span>'
                f'</summary><div class="note-rest">{remaining}</div></details>')
st.markdown(f'<div class="note-preview">{preview}</div>', unsafe_allow_html=True)

with st.form('question_form'):
    question = st.text_input('Ask a question about this note')
    submitted = st.form_submit_button('Ask question')

# A result belongs only to the note and question that produced it.
current_key = (selected_note.name, note_text, question.strip())
if st.session_state.get('result_key') != current_key:
    st.session_state.pop('qa_result', None)
if submitted:
    st.session_state.pop('qa_result', None)
    if not question.strip():
        st.warning('Enter an English question before submitting.')
    elif not note_text.strip():
        st.warning('The selected note is empty. Select another note.')
    else:
        try:
            with st.spinner('Running local Healthcare NLP. The first question may take a few minutes.'):
                response = get_qa_client().ask(question, note_text)
                evidence = select_evidence(note_text, question, response['answer'])
                st.session_state.qa_result = dict(response, **evidence)
                st.session_state.result_key = current_key
        except QAError as exc:
            st.error(str(exc))

result = st.session_state.get('qa_result')
if result:
    result = dict(result, **select_evidence(note_text, question, result['answer']))
    st.markdown('<h3 class="result-heading">Answer</h3>', unsafe_allow_html=True)
    st.write(result['answer'])
    st.caption('Generated by John Snow Labs Healthcare NLP: clinical_notes_qa_base_onnx_pipeline.')
    st.markdown('<h3 class="result-heading">Source evidence</h3>', unsafe_allow_html=True)
    st.write(f"Evidence status: {result['evidence_status']}")
    if result['evidence_status'] == 'partial_match_review_required':
        st.warning('The source list includes more items than the answer. The answer may be incomplete; review the full source list; only answer-related text is highlighted.')
    if result['evidence_matches']:
        st.caption(f"Matching source sentences: {len(result['evidence_matches'])}")
        st.markdown(highlighted_context(note_text, result), unsafe_allow_html=True)
    else:
        st.warning('No reliable source evidence was selected. The generated answer is unverified.')
